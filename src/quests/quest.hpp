#pragma once

// ============================================================================
// Includes
// ----------------------------------------------------------------------------

#include <string>
#include <vector>

// ============================================================================
// Namespaces
// ----------------------------------------------------------------------------

namespace mirelight {

// ============================================================================
// Enums
// ----------------------------------------------------------------------------

// ----------------------------------------------------------------------------
enum class Quest_type  {

    SIDE,
    MAIN
};

// ----------------------------------------------------------------------------
enum class Quest_state {
    LOCKED,
    AVAILABLE,
    ACTIVE,
    READY_TO_HAND_IN,
    COMPLETED
};

// ============================================================================
// Structs
// ----------------------------------------------------------------------------

// ----------------------------------------------------------------------------
struct Quest_reward {

    std::string type;
    std::string name;
    int         count = 1;
};

// ----------------------------------------------------------------------------
struct Quest {
    int                       id           = -1;
    int                       prerequisite = -1;  // -1 = always available
    Quest_type                type         = Quest_type::SIDE;
    std::string               npc;
    std::string               title;
    std::string               description;
    std::string               hand_in_text;
    std::vector<Quest_reward> rewards;
};

} // namespace mirelight
